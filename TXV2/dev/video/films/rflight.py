#!/usr/bin/env python3
"""Film RFLIGHT: the Rotorflight menu, a tour, then three things that save a day at the field: why it will not arm, a backup
first, and Bluetooth that keeps connecting. The facts are RFLIGHT.TXT's; the arming line and its list are the Teensy's own
words (TXV1B RF_FcSetup.h ArmShow / ArmingWhy: the main reason and "(and n more)" in yellow, the list in a message box over
the menu). Made with dev/video/filmkit.py.
18 Oct 2026, Malcolm: "Let's include the likely cure for tail-wag and other common set up issues." """
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from filmkit import Film, prefix, at, comp
from common import model_route, model_route_play
f = Film('RFLIGHT', 'Rotorflight', "The flight controller's settings, from the transmitter")
model_route(f, 'Rotorflight')
opn = prefix('8.txt', '8_open')                                       # (Ready to arm, in green; By Bluetooth)
f.shot('p', opn)
why = opn + 'arm.txt="Will not arm: Throttle is not at idle (and 1 more)"\narm.pco=65504\n'
f.shot('why', why)
f.shot('list', why + 'page PopupView\nvis b1,0\nDialog.txt="Why it will not arm:\\r\\n- Throttle is not at idle\\r\\n- The rescue switch is on"\n')
f.shot('conn', prefix('8.txt', '8_connecting'))                       # (joining: the arming line empty)
x, y, w, h = comp('RFView', 'arm'); ARM = (x + 70, y + h // 2)       # (the line's words start at its left)
f.line('title', "Rotorflight. Set up and tune your helicopter's flight controller, right from the transmitter.")
f.line('page', 'This is the Rotorflight menu. It sets up and tunes a flight controller running Rotorflight, at the field, with no laptop.')
f.line('needs', 'The model needs a Version two receiver: these pages use Bluetooth. Before you start, land, put the safety on, and switch the motor off.')
f.line('easy', "Easy tuning: the phone app's sliders, for quick tuning at the field.")
f.line('pids', 'P I Ds and Rates: the tuning of each bank. Each has a second page for the finer points.')
f.line('gov', "Governor: the head speed, and how it's held.")
f.line('rescue', 'Rescue: what happens when you flick the rescue switch.')
f.line('servos', 'Servos and Travel extents: the servos, and how far the swash and tail move.')
f.line('filters', 'Filters: gyro smoothing, and the vibration notches.')
f.line('adjust', 'Adjustments: a knob or a switch changes a setting in flight.')
f.line('switches', 'Switches: what each switch makes the flight controller do.')
f.line('copy', "Copy a bank copies one bank's tuning into another.")
f.line('battery', 'Battery and Black box: the flight pack, and the flight recorder.')
f.line('settings', "Settings, with the first-time basics: a new model's whole set-up.")
f.line('cli', "Command line opens Rotorflight's own command line. It needs the U S B cable from the receiver to the flight controller.")
f.line('how', "Every page works the same way. It reads the flight controller as it opens. Touch a box, type the new value, and press Save. It's written, read back to check, and stored.")
f.line('ok', 'OK goes back to the front page.')
f.line('why', "Now, a real lifesaver. The model won't arm? Don't guess: this line tells you why.")
f.line('list', 'Touch it, and you get every reason, up to four. Here, the throttle is not at idle, and the rescue switch is on.')
f.line('fixed', 'Put each one right, and the line turns green: Ready to arm.')
f.line('backup', 'Before you change anything, press Backup and restore, and keep a copy. If an experiment goes wrong, it puts your tune and set-up back.')
f.line('conn', "This box shows the Bluetooth link to the receiver. Stuck on connecting? Close the phone app if it's open: the receiver takes one Bluetooth connection at a time.")
f.prepare()
f.begin(); f.say('title', after=1.2)
model_route_play(f, 'Rotorflight', 'p')
f.say('page', 'Rotorflight.')
f.cap = None; f.say('needs', 'Safety on, motor off.')
f.point(*at('RFView', 'Easy'), 'easy', 'Easy tuning.')
f.point(*at('RFView', 'Pid'), 'pids', 'PIDs and Rates.')
f.point(*at('RFView', 'b2'), 'gov', 'Governor.')
f.point(*at('RFView', 'Rescue'), 'rescue', 'Rescue.')
f.point(*at('RFView', 'Servos'), 'servos', 'Servos, Travel extents.')
f.point(*at('RFView', 'Filters'), 'filters', 'Filters.')
f.point(*at('RFView', 'Adjust'), 'adjust', 'Adjustments.')
f.point(*at('RFView', 'Switches'), 'switches', 'Switches.')
f.point(*at('RFView', 'CopyBank'), 'copy', 'Copy a bank.')
f.point(*at('RFView', 'Battery'), 'battery', 'Battery, Black box.')
f.point(*at('RFView', 'Setup'), 'settings', 'Settings; first-time basics.')
f.point(*at('RFView', 'Cli'), 'cli', 'Command line.')
f.cap = None; f.say('how', 'Touch, type, Save.')
f.point(*at('RFView', 'b4'), 'ok', 'OK: the front page.')
f.show('why'); f.point(*ARM, 'why', "Tip: won't arm? Read this line.", after=0.3)
f.tap(*ARM, 'list'); f.say('list', 'Every reason, up to four.')
f.tap(*at('PopupView', 'b0'), 'p'); f.point(*ARM, 'fixed', 'Ready to arm.')
f.point(*at('RFView', 'b3'), 'backup', 'Tip: back up first.')
f.show('conn'); f.point(*at('RFView', 'pipe'), 'conn', 'Tip: close the phone app.')
f.end(); f.finish()
