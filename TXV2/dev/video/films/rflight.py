#!/usr/bin/env python3
"""Film RFLIGHT: the Rotorflight menu, a tour. The words are RFLIGHT.TXT's. Made with dev/video/filmkit.py."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from filmkit import Film, prefix, at
from common import model_route, model_route_play, rf_route, rf_route_play, keypad_shots, KEY
f = Film('RFLIGHT', 'Rotorflight', "The flight controller's settings, from the transmitter")
model_route(f, 'Rotorflight')
f.shot('p', prefix('8.txt', '8_open'))
f.line('title', "Rotorflight. The flight controller's settings, from the transmitter.")
f.line('page', 'This is the Rotorflight menu. It shows and changes the setup of a flight controller that runs Rotorflight, at the field, with no laptop. The model needs a Version two receiver: these pages use Bluetooth.')
f.line('before', 'Before you start, land, put the safety on, and switch the motor off.')
f.line('easy', "Easy tuning: the phone app's sliders, for tuning at the field.")
f.line('pids', 'P I Ds and Rates: the tuning of each bank. Each has a second page.')
f.line('gov', 'Governor: the head speed, and the governor.')
f.line('rescue', 'Rescue: what happens when you flick the rescue switch.')
f.line('servos', 'Servos and Travel extents: the servos, and how far the swash and tail move.')
f.line('filters', 'Filters: gyro smoothing, and the vibration notches.')
f.line('adjust', 'Adjustments: a knob or switch changes a setting in flight.')
f.line('switches', 'Switches: what each switch makes the flight controller do.')
f.line('copy', 'Copy a bank copies the tuning of one bank into another.')
f.line('battery', 'Battery and Black box: the flight pack, and the flight recorder.')
f.line('settings', "Settings, with the first time basics: a new model's whole set-up.")
f.line('arm', 'This line says whether the model will arm. Touch it to list the reasons.')
f.line('backup', 'Back up each setup you are happy with.')
f.line('how', "Each page reads the flight controller's values as it opens. Touch a box, type the new value, then press Save. The values are written, read back to check, and stored.")
f.line('ok', 'OK goes back to the front page.')
f.line('end', "That's the Rotorflight menu.")
f.prepare()
f.begin(); f.say('title', after=1.6)
model_route_play(f, 'Rotorflight', 'p')
f.say('page', 'Rotorflight.')
f.cap = None; f.say('before', 'Safety on, motor off.')
f.point(*at('RFView', 'Easy'), 'easy', 'Easy tuning.')
f.point(*at('RFView', 'Pid'), 'pids', 'PIDs and Rates.')
f.point(*at('RFView', 'b2'), 'gov', 'Governor.')
f.point(*at('RFView', 'Rescue'), 'rescue', 'Rescue.')
f.point(*at('RFView', 'Servos'), 'servos', 'Servos, Travel extents.')
f.point(*at('RFView', 'Filters'), 'filters', 'Filters.')
f.point(*at('RFView', 'Adjust'), 'adjust', 'Adjustments.')
f.point(*at('RFView', 'Switches'), 'switches', 'Switches.')
f.point(*at('RFView', 'CopyBank'), 'copy', 'Copy a bank.')
f.point(*at('RFView', 'Battery'), 'battery', 'Battery, Black box.')
f.point(*at('RFView', 'Setup'), 'settings', 'Settings; first-time basics.')
f.point(120, 368, 'arm', 'Will it arm?')
f.point(*at('RFView', 'b3'), 'backup', 'Backup & restore.')
f.cap = None; f.say('how', 'Touch, type, Save.')
f.point(*at('RFView', 'b4'), 'ok', 'OK.')
f.end('end'); f.finish()
