#!/usr/bin/env python3
"""Film ONESWICH: one switch's job, a tour. The words are ONESWICH.TXT's. Made with dev/video/filmkit.py."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from filmkit import Film, prefix, at
from common import model_route, model_route_play, tx_route, tx_route_play, FRONT_NO_MODEL
f = Film('ONESWICH', "A switch's job", 'Choosing what one switch does')
tx_route(f, 'Switches')
f.shot('sw', prefix('53.txt', '53_open')); f.shot('p', prefix('54.txt', '54_open'))
f.line('title', "A switch's job. Choosing what one switch does.")
f.line('switches', "This is the Switches page. Touch a switch's job to change it.")
f.line('page', "Choose this switch's job, then press OK to save it. One job per switch: giving a job to this switch takes it from any switch that had it.")
f.line('banks', 'Banks one two three: away is bank one, mid is bank two, near is bank three.')
f.line('motor', 'Bank four and Motor: away is motor on. Mid is bank four with the motor on. Near is bank four with the motor off.')
f.line('safety', 'Safety: near is safety off. With a Rotorflight model, safety off arms the model.')
f.line('rates', 'Rates: away, mid and near pick rates one, two and three.')
f.line('buddy', 'Buddy hands control to the buddy. A spring return switch is best.')
f.line('channel', "Channel nine and the others: the switch becomes that channel's input.")
f.line('reversed', 'Reversed turns the switch round, so that near and away swap.')
f.line('ok', 'Press OK to save.')
f.line('end', "That's how to choose a switch's job.")
f.prepare()
f.begin(); f.say('title', after=1.6)
tx_route_play(f, 'Switches', 'sw')
f.say('switches', "Touch a switch's job.", after=0.3); f.tap(*at('SwitchesView', 'sw3'), 'p')
f.say('page', 'One job per switch.')
f.point(*at('OneSwitchView', 'r1'), 'banks', 'Banks 1 2 3.')
f.point(*at('OneSwitchView', 'r2'), 'motor', 'Bank 4 & Motor.')
f.point(*at('OneSwitchView', 'r7'), 'safety', 'Safety.')
f.point(*at('OneSwitchView', 'r8'), 'rates', 'Rates.')
f.point(*at('OneSwitchView', 'r9'), 'buddy', 'Buddy.')
f.point(*at('OneSwitchView', 'r3'), 'channel', 'A channel input.')
f.point(*at('OneSwitchView', 't99'), 'reversed', 'Reversed.')
f.point(*at('OneSwitchView', 'b10'), 'ok', 'OK saves.')
f.end('end'); f.finish()
