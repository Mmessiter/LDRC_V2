#!/usr/bin/env python3
"""Film BASICS4: the ESC's throttle calibration - the whole procedure, then when it is needed and why the hold is safe. The
facts are BASICS4.TXT's (blades off, pack unplugged, USB power; the hold lapses a second after the last renewal; nothing is
saved: the ESC remembers the range); the question and the fourth line's words are RF_EscCal.h's (EcalShow: "MINIMUM: wait
for the confirmation beeps", "Calibrated: unplug the battery"). Made with dev/video/filmkit.py.
18 Oct 2026: starts on the Rotorflight menu (Settings, First-time basics, Next x3); livelier words; "In practice"; no closing line."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from filmkit import Film, prefix, at
from common import rf_route, rf_route_play, rfs
f = Film('BASICS4', 'Throttle calibration', 'Teaching the ESC the throttle range')
rf_route(f, 'Settings ...')
held = rfs('77.txt', '80_held')
ready = held.replace('tn3.txt="FULL THROTTLE held: plug the flight battery in"\nb2.txt="Minimum"', 'tn3.txt="Ready: tap Full throttle to begin"\nb2.txt="Full throttle"')
assert ready != held
f.shot('s', rfs('61.txt', '61_open'))
f.shot('b', rfs('77.txt', '77_ready', 'tn1.txt="Clockwise"\ntn2.txt="Variable pitch"\n'))
f.shot('b2', rfs('77.txt', '78_ready')); f.shot('b3', rfs('77.txt', '79_ready'))
f.shot('p', ready); f.shot('held', held)
f.shot('ask', ready + 'page PopupView\nDialog.txt="Blades OFF or pinion out? Flight pack\\r\\nUNPLUGGED? Flight controller on USB power?\\r\\nIt holds FULL throttle until you tap\\r\\n\'Minimum\'. Plug the flight battery in\\r\\nonce it is held."\n')
f.shot('minw', held + 'tn3.txt="MINIMUM: wait for the confirmation beeps"\nb2.txt="Full throttle"\n')
f.shot('done', held + 'tn3.txt="Calibrated: unplug the battery"\nb2.txt="Full throttle"\n')
f.line('title', 'Throttle calibration. Teach the E S C the throttle range Rotorflight sends.')
f.line('s', 'This is the Rotorflight settings page. Press First time basics.')
f.line('b', 'This is the First time basics page. Press Next.')
f.line('b2', 'This is the Gear ratio page. Press Next again.')
f.line('b3', 'This is the Ports page. Press Next once more.')
f.line('page', "And this is the Throttle calibration page. It teaches the E S C the throttle range, and you won't need a computer.")
f.line('before', 'Safety first. Blades off, or the pinion out of the main gear. The flight pack unplugged, and the flight controller on U S B power. Safety on, and nobody at the sticks.')
f.line('full', 'Then tap Full throttle.')
f.line('ask', 'It asks you to check. Then press OK.')
f.line('heldnow', 'The fourth line says full throttle, held.')
f.line('plug', "Now plug the flight pack in. The E S C sees full throttle as it wakes, and beeps to say it's learned the top.")
f.line('min', 'Then tap Minimum.')
f.line('minw', "The E S C sees minimum, and beeps again: it's learned the bottom.")
f.line('done', 'Calibrated! Unplug the battery. Nothing needs saving: the E S C itself remembers the range.')
f.line('when', "When do you need it? Usually once for each new E S C: its instructions will say. And again if the motor starts too early, or too late, on the throttle.")
f.line('safe', "And don't worry about that hold. Leave the page, lose the link, or flick the safety, and it's gone a second later.")
f.prepare()
f.begin(); f.say('title', after=1.2)
rf_route_play(f, 'Settings ...', 's')
f.say('s', 'Press First-time basics.', after=0.3); f.tap(*at('RFSetupView', 'b5'), 'b')
f.say('b', 'Press Next.', after=0.3); f.tap(*at('BasicsView', 'b2'), 'b2')
f.say('b2', 'Press Next.', after=0.3); f.tap(*at('Basics2View', 'b2'), 'b3')
f.say('b3', 'Press Next.', after=0.3); f.tap(*at('PortsView', 'b2'), 'p')
f.say('page', 'Throttle calibration.')
f.point(*at('EscCalView', 'tn0'), 'before', 'Blades off; pack unplugged; safety on.')
f.cap = None; f.say('full', "Tap 'Full throttle'.", after=0.3); f.tap(*at('EscCalView', 'b2'), 'ask')
f.say('ask', 'Check, then OK.', after=0.3); f.tap(*at('PopupView', 'b0'), 'held')
f.point(*at('EscCalView', 'tn3'), 'heldnow', 'Full throttle, held.')
f.cap = None; f.say('plug', 'Plug the pack in: the ESC beeps.')
f.cap = None; f.say('min', "Tap 'Minimum'.", after=0.3); f.tap(*at('EscCalView', 'b2'), 'minw')
f.point(*at('EscCalView', 'tn3'), 'minw', 'It beeps again.')
f.under('done'); f.hold(0.6); f.say('done', 'Calibrated: unplug the battery.')
f.cap = None; f.say('when', 'Tip: once for each new ESC.')
f.say('safe', 'Tip: the hold lets go by itself.')
f.end(); f.finish()
