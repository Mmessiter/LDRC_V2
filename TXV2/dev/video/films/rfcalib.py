#!/usr/bin/env python3
"""Film RFCALIB: calibrating the level - a tour, the calibration, then curing a drift. The facts are RFCALIB.TXT's; the
question and the busy lines are RF_FcSetup.h's (CalibrateNow: "Calibrating: keep it still ..." then "Calibrated: roll ...,
pitch ... degrees."); "Calibrate level first" is the arming line's words (ArmWhy). Made with dev/video/filmkit.py.
18 Oct 2026: starts on the Rotorflight menu (Settings, then Calibrate); livelier words; "In practice"; no closing line (Malcolm)."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from filmkit import Film, prefix, at
from common import rf_route, rf_route_play, rfs, SAVE_SHOWN
f = Film('RFCALIB', 'Calibrate the level', 'Which way is level, for self-levelling and rescue')
rf_route(f, 'Settings ...')
lvl = rfs('74.txt', '74_level', 'tn2.txt="0.0"\ntn3.txt="0.0"\nvis b3,0\n')        # (level, the trims at nought, nothing changed)
after = lvl + 'tn0.txt="Roll -0.1   Pitch 0.2 deg"\n'                                  # (just after a calibration: both near nought)
f.shot('willnot', prefix('8.txt', '8_open') + 'arm.txt="Will not arm: Calibrate level first"\narm.pco=65504\n')
f.shot('s', rfs('61.txt', '61_open')); f.shot('p', lvl)
f.shot('ask', lvl + 'page PopupView\nDialog.txt="Is the model level and perfectly still?\\r\\n(Best done on a flat desk, before\\r\\nthe board goes into the model.)"\n')
f.shot('cal', lvl + 'vis busy,1\nbusy.txt="Calibrating: keep it still ..."\n')
f.shot('done', after + 'vis busy,1\nbusy.txt="Calibrated: roll -0.1, pitch 0.2 degrees."\n')
f.shot('after', after)
f.shot('trim', after + 'tn3.txt="0.5"\n' + SAVE_SHOWN)
f.line('title', 'Calibrate the level. Show the flight controller which way is level, for self levelling and rescue.')
f.line('s', 'This is the Rotorflight settings page. Press Calibrate.')
f.line('page', "This is the Calibrate page. It's the same in every bank.")
f.line('live', 'On the left, the roll and pitch the flight controller sees, live. The line below says Level when both are within two degrees.')
f.line('trims', 'On the right, the level trims: small corrections to the level that self levelling and rescue aim for.')
f.line('flat', 'To calibrate, stand the board, or the helicopter, flat and perfectly still. A flat desk is best, before the board goes into the model: a helicopter rarely sits truly level.')
f.line('press', 'Then tap Calibrate level.')
f.line('ask', 'Check, and answer OK.')
f.line('still', 'Keep it still for a few seconds.')
f.line('done', "Calibrated! The new level is stored in the flight controller.")
f.line('arm', "Here's when you'll need it. If the Rotorflight menu's arming line says Will not arm: Calibrate level first, this is the page to come to.")
f.line('drift', 'Does self levelling, or rescue, drift to one side? Calibrate again first, on a flat desk.')
f.line('trim', 'Still drifting a little? Add a small level trim, half a degree at a time, and test it again, high up.')
f.line('knob', 'You can even put the level trims on a knob, with Adjustments, and trim it in the air.')
f.line('save', 'Save writes the trims to the flight controller, and reads them back.')
f.prepare()
f.begin(); f.say('title', after=1.2)
rf_route_play(f, 'Settings ...', 's')
f.say('s', 'Press Calibrate.', after=0.3); f.tap(*at('RFSetupView', 'b6'), 'p')
f.say('page', 'Calibrate.')
f.point(*at('LevelView', 'tn0'), 'live', 'The live level.')
f.point(*at('LevelView', 'h1'), 'trims', 'Level trims.')
f.cap = None; f.say('flat', 'Flat and perfectly still.')
f.say('press', "Tap 'Calibrate level'.", after=0.3); f.tap(*at('LevelView', 'b2'), 'ask')
f.say('ask', 'Press OK.', after=0.3); f.tap(*at('PopupView', 'b0'), 'cal')
f.say('still', 'Keep it still.')
f.under('done'); f.hold(0.6); f.say('done', 'Calibrated.', after=1.0)
f.show('willnot'); f.point(*at('RFView', 'arm'), 'arm', "Tip: 'Calibrate level first'?")
f.show('after'); f.say('drift', 'Tip: drifts? Calibrate again.')
f.show('trim'); f.point(*at('LevelView', 'tn3'), 'trim', 'Tip: a small trim, then test.')
f.cap = None; f.say('knob', 'Tip: or trim with a knob.')
f.point(*at('LevelView', 'b3'), 'save', 'Save.')
f.end(); f.finish()
