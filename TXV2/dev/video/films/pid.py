#!/usr/bin/env python3
"""Film PID: the PIDs page - a tour, then the cures pilots come here for: tail wag (yaw P about ten per cent lower, typed on
the keypad and saved), a fast wobble (less P), drift (a little more I), and a bank kept as a safe fallback. The facts are
PID.TXT's; the gains are RAW 420 MCM's own (scenario 40, RXV2 dev/snapshots raw420_snapshot_20260817: yaw 150 165 25 0);
the keypad is keybdB (its value, Delete, digits, OK; the question "Yaw P" is n8's own touch event); Save is
SendEditedPIDs' (RF_PIDs.h: the boxes grey, "Sending edited PIDs ...", then back). Made with dev/video/filmkit.py.
18 Oct 2026, Malcolm: "Let's include the likely cure for tail-wag and other common set up issues." """
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from filmkit import Film, prefix, at
from common import rf_route, rf_route_play, keypad_shots, KEY
from illus import Art
f = Film('PID', 'PIDs', "The flight controller's P, I and D gains")
art = Art(f)
rf_route(f, 'PIDs ...')
opn = prefix('40.txt', '40_open')
GREY = ''.join('n%d.pco=33840\n' % i for i in range(17))
BLACK = ''.join('n%d.pco=0\n' % i for i in range(17))
f.shot('p', opn)
keypad_shots(f, opn, 40, 'n8', 18, ['150', '15', '1', '13', '135'])   # (Yaw P: Delete twice, then 3 and 5)
f.shot('e', opn + 'n8.val=135\nvis b3,1\n')
f.shot('s', opn + 'n8.val=135\n' + GREY + 'busy.txt="Sending edited PIDs ..."\nvis busy,1\nvis b2,0\nvis b3,0\n')
f.shot('d', opn + 'n8.val=135\n' + BLACK + 'vis busy,0\nvis b2,1\nvis b3,0\n')
f.line('title', "P I Ds. The heart of how your helicopter flies: the flight controller's P I D gains.")
f.line('page', 'This is the P I Ds page: the gains for roll, pitch and yaw, for the bank shown at the top left.')
f.line('bank', 'Choose the bank with the bank switch, and wait a moment while it loads.')
f.line('p', 'P: how hard it corrects. Too much gives a fast wobble.')
f.line('i', 'I: how firmly it holds against drift and wind.')
f.line('d', 'D: damping, against overshoot.')
f.line('ff', 'F F, feed forward, answers the stick at once.')
f.line('boost', 'Boost adds a kick on quick stick moves. And H S I gain builds up an automatic trim in fast forward flight.')
f.line('plus', 'P I D plus has the finer points, for the same bank.')
f.line('ok', 'OK goes back to the Rotorflight menu.')
f.line('wag', "Now, the problem everyone meets sooner or later: tail wag. A fast twitch of the tail, from side to side.")
f.line('cause', "Usually the yaw gain is too high, so the gyro over-corrects, back and forth. The cure: lower yaw P by about ten per cent.")
f.line('yawp', "Here, yaw P is a hundred and fifty. Ten per cent lower is a hundred and thirty five.")
f.line('pad', 'Touch the box. The keypad shows its name and value. Press Delete, type the new number, and press OK.')
f.line('save', "Then press Save. It's written to the flight controller, read back to check, and stored.")
f.line('warn', 'Save before you move the bank switch, or the change is lost.')
f.line('fly', "Now fly it. If the wag's gone, but the tail feels soft on its stops, go back half way.")
f.line('wobble', "A fast wobble on roll or pitch? That's usually P a little too high. Bring it down in small steps.")
f.line('drift', "Drifts, or won't hold its line in the wind? A little more I often helps.")
f.line('fallback', "And here's a clever one. Tune in one bank, and leave another untouched, as a safe fallback. One flick of the bank switch takes you back to what worked.")
f.prepare()
f.begin(); f.say('title', after=1.2)
rf_route_play(f, 'PIDs ...', 'p')
f.say('page', 'PIDs.')
f.point(*at('PIDView', 't9'), 'bank', 'The bank.')
f.point(*at('PIDView', 't5'), 'p', 'P.')
f.point(*at('PIDView', 't6'), 'i', 'I.')
f.point(*at('PIDView', 't7'), 'd', 'D.')
f.point(*at('PIDView', 't8'), 'ff', 'FF.')
f.point(*at('PIDView', 't12'), 'boost', 'Boost; HSI gain.')
f.point(*at('PIDView', 'b2'), 'plus', 'PID + ...')
f.point(*at('PIDView', 'b1'), 'ok', 'OK.')
# ---- in practice: tail wag, cured on this page
f.show(art.tail_wag(0)); f.anim(art.tail_wag, 3.0); f.say('wag', 'Tip: tail wag.')
f.say('cause', 'Tip: lower yaw P about 10 %.')
f.show('p'); f.point(*at('PIDView', 't3'), 'yawp', 'Yaw P: 150 becomes 135.', after=0.3)
f.tap(*at('PIDView', 'n8'), 'kp0'); f.say('pad', 'Delete, type, OK.', after=0.3)
f.tap(*KEY['Delete']); f.under('kp1'); f.hold(0.4); f.tap(*KEY['Delete']); f.under('kp2'); f.hold(0.4)
f.tap(*KEY['3']); f.under('kp3'); f.hold(0.4); f.tap(*KEY['5']); f.under('kp4'); f.hold(0.6); f.tap(*KEY['OK'], 'e')
f.say('save', 'Press Save.', after=0.3); f.tap(*at('PIDView', 'b3')); f.under('s'); f.hold(1.4); f.under('d'); f.hold(0.6)
f.cap = None; f.say('warn', 'Save before the bank switch.')
f.say('fly', 'Tip: then fly it.')
f.point(*at('PIDView', 'n0'), 'wobble', 'Tip: fast wobble? Less P.')
f.point(*at('PIDView', 'n1'), 'drift', 'Tip: drifts? A little more I.')
f.point(*at('PIDView', 't9'), 'fallback', 'Tip: keep a safe bank.')
f.end(); f.finish()
