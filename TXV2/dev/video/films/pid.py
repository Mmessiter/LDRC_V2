#!/usr/bin/env python3
"""Film PID: the PIDs page, and changing a value with the keypad (keybdB: its value, Delete, a digit, OK). The words are
PID.TXT's; 50 to 55 is scenario 40's own edit (40_edited). Made with dev/video/filmkit.py."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from filmkit import Film, prefix, at
from common import model_route, model_route_play, rf_route, rf_route_play, keypad_shots, KEY
f = Film('PID', 'PIDs', "The flight controller's P, I and D gains")
rf_route(f, 'PIDs ...')
opn = prefix('40.txt', '40_open')
f.shot('p', opn); keypad_shots(f, opn, 40, 'n0', 10, ['50', '5', '55'])
f.shot('e', prefix('40.txt', '40_edited')); f.shot('s', prefix('40.txt', '40_sending')); f.shot('d', opn + 'n0.val=55\n')
f.line('title', "P I Ds. The flight controller's P I D gains.")
f.line('page', 'This is the P I Ds page: the gains for roll, pitch and yaw, for the bank shown at the top left.')
f.line('bank', 'Choose the bank with the bank switch, and wait while it loads.')
f.line('p', 'P: how hard it corrects. Too much gives a fast wobble. I: how firmly it holds against drift and wind. D: damping, against overshoot.')
f.line('ff', 'F F, feed forward, answers the stick at once.')
f.line('touch', 'To change a value, touch its box.')
f.line('pad', 'The keypad shows its value. Press Delete, type the new one, and press OK.')
f.line('save', 'Then press Save. The values are written to the flight controller, read back to check, and stored.')
f.line('warn', 'Save before you move the bank switch: a move loads the other bank, and unsaved changes are lost.')
f.line('plus', 'P I D plus opens the advanced settings, for the same bank.')
f.line('ok', 'OK goes back to the Rotorflight page.')
f.line('end', "That's the P I Ds page.")
f.prepare()
f.begin(); f.say('title', after=1.6)
rf_route_play(f, 'PIDs ...', 'p')
f.say('page', 'PIDs.')
f.point(*at('PIDView', 't9'), 'bank', 'The bank.')
f.point(*at('PIDView', 't5'), 'p', 'P, I, D.')
f.point(*at('PIDView', 't8'), 'ff', 'FF.')
f.cap = None; f.say('touch', 'Touch a box.', after=0.3); f.tap(*at('PIDView', 'n0'), 'kp0')
f.say('pad', 'Delete, type, OK.', after=0.3)
f.tap(*KEY['Delete']); f.under('kp1'); f.hold(0.5); f.tap(*KEY['5']); f.under('kp2'); f.hold(0.5); f.tap(*KEY['OK'], 'e')
f.say('save', 'Press Save.', after=0.3); f.tap(*at('PIDView', 'b3')); f.under('s'); f.hold(1.4); f.under('d'); f.hold(0.6)
f.cap = None; f.say('warn', 'Save before you move the bank switch.')
f.point(*at('PIDView', 'b2'), 'plus', 'PID +.')
f.point(*at('PIDView', 'b1'), 'ok', 'OK.')
f.end('end'); f.finish()
